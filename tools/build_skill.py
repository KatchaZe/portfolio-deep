"""
Build the ifa-stock-analysis skill from the app's own code.

    python -m tools.build_skill          copy the engine into the skill (after any engine change)
    python -m tools.build_skill --check  exit 1 if the skill's copy differs from the app (CI)
    python -m tools.build_skill --zip    also write dist/ifa-stock-analysis.zip for claude.ai

The skill values a stock with the same code as the dashboard: scripts/value.py runs
pipeline.finish + the DEEP engine from scripts/app/, a copy of the modules those two
import (found by reading every import statement, nested ones included). The copy is
generated; edit the app, never scripts/app/.
"""
import ast
import hashlib
import os
import shutil
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "skill", "ifa-stock-analysis")
APP_COPY = os.path.join(SKILL, "scripts", "app")
DIST = os.path.join(ROOT, "dist", "ifa-stock-analysis.zip")
SEEDS = ("pipeline.finish", "domain.engine")
MANIFEST = "MANIFEST.txt"


def _module_file(name):
    base = os.path.join(ROOT, *name.split("."))
    for path in (base + ".py", os.path.join(base, "__init__.py")):
        if os.path.isfile(path):
            return path
    return None


def _imports(path):
    """Every repo module `path` imports, at any depth in the file."""
    tree = ast.parse(open(path, encoding="utf-8").read(), path)
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level:                      # relative: resolve against this package
                pkg = os.path.relpath(os.path.dirname(path), ROOT).replace(os.sep, ".")
                parts = pkg.split(".")[: len(pkg.split(".")) - node.level + 1]
                mod = ".".join(parts + ([node.module] if node.module else []))
            else:
                mod = node.module
            found.add(mod)
            found.update(mod + "." + a.name for a in node.names)   # `from domain import one_time`
    return {m for m in found if _module_file(m)}


def closure():
    """Repo-relative paths of the seeds and everything they import, plus each
    package's __init__.py on the way down."""
    todo, seen = list(SEEDS), set()
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        parts = name.split(".")
        todo.extend(".".join(parts[:i]) for i in range(1, len(parts)))
        todo.extend(_imports(_module_file(name)))
    return sorted(os.path.relpath(_module_file(m), ROOT).replace(os.sep, "/") for m in seen)


def _sha(path):
    with open(path, "rb") as fh:
        return hashlib.sha1(fh.read()).hexdigest()[:12]


def _manifest(files):
    lines = ["Generated by tools/build_skill.py from the portfolio-deep app. Do not edit:",
             "change the app, then run  python -m tools.build_skill", ""]
    lines += [f"{_sha(os.path.join(ROOT, f))}  {f}" for f in files]
    return "\n".join(lines) + "\n"


def _copied_files():
    out = []
    for base, dirs, files in os.walk(APP_COPY):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for fn in files:
            if fn != MANIFEST:
                out.append(os.path.relpath(os.path.join(base, fn), APP_COPY).replace(os.sep, "/"))
    return sorted(out)


def check():
    """Differences between the app and the skill's copy, as readable lines."""
    want = closure()
    problems = []
    have = set(_copied_files())
    for f in want:
        dst = os.path.join(APP_COPY, f)
        if f not in have:
            problems.append("missing in skill: " + f)
        elif _sha(dst) != _sha(os.path.join(ROOT, f)):
            problems.append("stale in skill: " + f)
    problems += ["not in the app's closure any more: " + f for f in sorted(have - set(want))]
    return problems


def build():
    files = closure()
    if os.path.isdir(APP_COPY):
        shutil.rmtree(APP_COPY)
    for f in files:
        dst = os.path.join(APP_COPY, f)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, f), dst)
    with open(os.path.join(APP_COPY, MANIFEST), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(_manifest(files))
    return files


def write_zip():
    os.makedirs(os.path.dirname(DIST), exist_ok=True)
    with zipfile.ZipFile(DIST, "w", zipfile.ZIP_DEFLATED) as z:
        for base, dirs, files in os.walk(SKILL):
            dirs[:] = sorted(d for d in dirs if d != "__pycache__")
            for fn in sorted(files):
                path = os.path.join(base, fn)
                z.write(path, os.path.join("ifa-stock-analysis", os.path.relpath(path, SKILL)))
    return DIST


def main(argv):
    if "--check" in argv:
        problems = check()
        for p in problems:
            print(p)
        if problems:
            print("skill copy is out of date: run  python -m tools.build_skill")
            return 1
        print("skill engine copy matches the app (%d files)" % len(closure()))
        return 0
    files = build()
    print("copied %d app modules into %s" % (len(files), os.path.relpath(APP_COPY, ROOT)))
    if "--zip" in argv:
        print("wrote", os.path.relpath(write_zip(), ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
